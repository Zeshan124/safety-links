/**
 * Returns all posts sorted by date descending.
 */
export function getAllPosts() {
  return [...blogPosts].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}

/**
 * Returns featured posts only.
 */
export function getFeaturedPosts() {
  return getAllPosts().filter((p) => p.featured);
}

/**
 * Returns a single post by slug, or undefined if not found.
 * @param {string} slug
 */
export function getPostBySlug(slug) {
  return blogPosts.find((p) => p.slug === slug);
}

/**
 * Returns all unique categories.
 */
export function getAllCategories() {
  return ["All", ...new Set(blogPosts.map((p) => p.category))];
}
